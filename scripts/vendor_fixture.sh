#!/usr/bin/env bash
# Vendor the SQL fixture from the metaxisdata source repository, renaming its
# databases and schemas to the names this demo uses.
#
# The upstream fixture is a four-hop ETL chain (MySQL -> PostgreSQL -> StarRocks) whose
# SQL already exercises every construct the lineage analyzers have to cope with, so the
# demo reuses it rather than inventing its own data. Only qualified names change:
#
#   MySQL       e2e_ods                              -> shop
#   PostgreSQL  database e2e                         -> warehouse
#               schemas e2e_ods/e2e_dwd/e2e_ads      -> ods/dwd/ads
#   StarRocks   e2e_ods / e2e_ads                    -> ods / ads
#
# Table and view names are kept as they are.
#
# Usage: scripts/vendor_fixture.sh [path-to-metaxisdata-checkout]
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

SRC="${1:-${METAXISDATA_SRC:-../../gocode/metaxisdata}}"
UPSTREAM="$SRC/test/e2e_etl"

if [[ ! -d "$UPSTREAM" ]]; then
  echo "vendor_fixture: no fixture at $UPSTREAM" >&2
  echo "pass the metaxisdata checkout as the first argument, or set METAXISDATA_SRC" >&2
  exit 1
fi

mkdir -p fixture/mysql fixture/pg fixture/starrocks

# MySQL: the source database is `shop`.
sed -E 's/\be2e_ods\b/shop/g' \
  "$UPSTREAM/mysql/10_schema.sql" > fixture/mysql/10_schema.sql
sed -E 's/\be2e_ods\b/shop/g' \
  "$UPSTREAM/mysql/20_seed.sql" > fixture/mysql/20_seed.sql
sed -E 's/\be2e_ods\b/shop/g' \
  "$UPSTREAM/mysql/90_views.sql" > fixture/mysql/90_views.sql

# PostgreSQL: the database is `warehouse`, the layers are ods/dwd/ads.
for f in 05_ods_ddl 10_dwd_ddl 20_dwd_load 30_ads_ddl 40_ads_load 50_experimental_pg_features; do
  sed -E -e 's/\be2e_ods\b/ods/g' -e 's/\be2e_dwd\b/dwd/g' -e 's/\be2e_ads\b/ads/g' \
    -e 's/\be2e\b/warehouse/g' \
    "$UPSTREAM/pg/$f.sql" > "fixture/pg/$f.sql"
done

# StarRocks: serving databases ods/ads.
for f in 10_ods_ddl 20_ads_ddl; do
  sed -E -e 's/\be2e_ods\b/ods/g' -e 's/\be2e_ads\b/ads/g' \
    "$UPSTREAM/starrocks/$f.sql" > "fixture/starrocks/$f.sql"
done

# Record where the fixture came from, so it can be re-vendored deliberately.
{
  echo "Vendored from the metaxisdata repository."
  echo "repo:   https://github.com/Ranxy/metaxisdata"
  echo "commit: $(git -C "$SRC" rev-parse HEAD 2>/dev/null || echo unknown)"
  echo "path:   test/e2e_etl/{mysql,pg,starrocks}"
  echo "generated by: scripts/vendor_fixture.sh"
} > fixture/UPSTREAM

if grep -rInE '\be2e(_ods|_dwd|_ads)?\b' fixture --include='*.sql'; then
  echo "vendor_fixture: upstream names are still present above" >&2
  exit 1
fi

echo "vendor_fixture: wrote fixture/{mysql,pg,starrocks} from $UPSTREAM"
